// Helper to look up a project by either its ID, aliases, or slug
export function getProjectById(idOrSlug) {
  if (!idOrSlug) return projectsData[0];
  const target = String(idOrSlug).toLowerCase().trim();

  // 1. Direct match by id
  const direct = projectsData.find((p) => String(p.id).toLowerCase() === target);
  if (direct) return direct;

  // 2. Match by alias
  const byAlias = projectsData.find(
    (p) => p.aliases && p.aliases.some((a) => a.toLowerCase() === target)
  );
  if (byAlias) return byAlias;

  // 3. Fallback: match by title partial or numeric index
  const num = parseInt(target, 10);
  if (!isNaN(num) && num > 0) {
    const wrappedIdx = (num - 1) % projectsData.length;
    return projectsData[wrappedIdx];
  }

  // 4. Fallback: match by title
  const byTitle = projectsData.find((p) =>
    p.title.toLowerCase().replace(/[^a-z0-9]/g, "-").includes(target)
  );
  if (byTitle) return byTitle;

  // Default to first project if totally unresolvable
  return projectsData[0];
}
